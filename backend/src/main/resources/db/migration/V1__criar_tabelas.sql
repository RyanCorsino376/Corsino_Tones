-- Stage 07 schema. Constraint names are read by the JPA adapters to translate database errors.

CREATE TABLE usuario (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome       VARCHAR(100) NOT NULL,
    email      VARCHAR(254) NOT NULL,
    senha_hash VARCHAR(100) NOT NULL,
    perfil     VARCHAR(10)  NOT NULL DEFAULT 'COMUM',
    criado_em  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_usuario PRIMARY KEY (id),
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('COMUM', 'ADMIN'))
);

CREATE TABLE equipamento (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    marca  VARCHAR(50) NOT NULL,
    modelo VARCHAR(50) NOT NULL,
    CONSTRAINT pk_equipamento PRIMARY KEY (id),
    CONSTRAINT uk_equipamento_marca_modelo UNIQUE (marca, modelo)
);

-- The id is the slug of estilo, marca and modelo, built by the server at creation.
CREATE TABLE pack (
    id             VARCHAR(80)  NOT NULL,
    nome           VARCHAR(120) NOT NULL,
    estilo         VARCHAR(30)  NOT NULL,
    descricao      VARCHAR(500) NOT NULL,
    preco_centavos INTEGER      NOT NULL,
    equipamento_id BIGINT       NOT NULL,
    CONSTRAINT pk_pack PRIMARY KEY (id),
    CONSTRAINT uk_pack_estilo_equipamento UNIQUE (estilo, equipamento_id),
    CONSTRAINT ck_pack_preco_centavos CHECK (preco_centavos >= 0),
    CONSTRAINT fk_pack_equipamento FOREIGN KEY (equipamento_id) REFERENCES equipamento (id) ON DELETE RESTRICT
);

-- arquivo_chave: key of the preset file in MinIO (later slice); NULL until then and never part of the JSON.
CREATE TABLE preset (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nome            VARCHAR(120) NOT NULL,
    descricao       VARCHAR(500) NOT NULL,
    data_publicacao DATE         NOT NULL,
    pack_id         VARCHAR(80)  NOT NULL,
    arquivo_chave   VARCHAR(255),
    CONSTRAINT pk_preset PRIMARY KEY (id),
    CONSTRAINT fk_preset_pack FOREIGN KEY (pack_id) REFERENCES pack (id) ON DELETE RESTRICT
);

CREATE TABLE pedido (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    usuario_id     BIGINT      NOT NULL,
    status         VARCHAR(10) NOT NULL,
    total_centavos INTEGER     NOT NULL,
    criado_em      TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_pedido PRIMARY KEY (id),
    CONSTRAINT ck_pedido_status CHECK (status IN ('pendente', 'pago')),
    CONSTRAINT ck_pedido_total_centavos CHECK (total_centavos >= 0),
    CONSTRAINT fk_pedido_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE RESTRICT
);

-- preco_centavos freezes the pack price at purchase time.
CREATE TABLE item_pedido (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    pedido_id      BIGINT      NOT NULL,
    pack_id        VARCHAR(80) NOT NULL,
    preco_centavos INTEGER     NOT NULL,
    CONSTRAINT pk_item_pedido PRIMARY KEY (id),
    CONSTRAINT uk_item_pedido_pack UNIQUE (pedido_id, pack_id),
    CONSTRAINT ck_item_pedido_preco_centavos CHECK (preco_centavos >= 0),
    CONSTRAINT fk_item_pedido_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (id) ON DELETE CASCADE,
    CONSTRAINT fk_item_pedido_pack FOREIGN KEY (pack_id) REFERENCES pack (id) ON DELETE RESTRICT
);

-- PostgreSQL does not index foreign keys on its own; these are not the leading column of any other index.
CREATE INDEX ix_pack_equipamento ON pack (equipamento_id);
CREATE INDEX ix_preset_pack ON preset (pack_id);
CREATE INDEX ix_pedido_usuario ON pedido (usuario_id);
CREATE INDEX ix_item_pedido_pack ON item_pedido (pack_id);
